/** 章に対応する原文をまとめて */
export function srcOf(chapter: ChapterId): SourceLine[] {
  return SOURCE.filter((s) => s.chapter === chapter);
}

/** これまでに到達した章までの原文（原作ログ用） */
export function unlockedSource(unlocked: ChapterId, order: readonly ChapterId[]): SourceLine[] {
  const max = order.indexOf(unlocked);
  return SOURCE.filter((s) => order.indexOf(s.chapter) <= max);
}
